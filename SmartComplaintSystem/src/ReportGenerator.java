
import javax.swing.*;
import java.awt.Desktop;
import java.io.File;
import java.nio.file.Files;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

public class ReportGenerator {

    public static void generate(ComplaintManager manager) {

        try {

            StringBuilder html = new StringBuilder();

            html.append("<html><head><title>Complaint Report</title>");

            html.append("<style>");
            html.append("body{font-family:Arial;margin:30px;color:#222;}");
            html.append("h1{text-align:center;color:#17365D;}");
            html.append("h3{color:#17365D;}");
            html.append(".cards{display:flex;gap:12px;margin:20px 0;}");
            html.append(".card{flex:1;padding:15px;background:#EAF2F8;");
            html.append("text-align:center;border-radius:8px;}");
            html.append("table{width:100%;border-collapse:collapse;");
            html.append("font-size:12px;}");
            html.append("th{background:#17365D;color:white;}");
            html.append("th,td{border:1px solid #bbb;padding:9px;");
            html.append("text-align:left;}");
            html.append("tr:nth-child(even){background:#F2F5F7;}");
            html.append(".footer{text-align:center;margin-top:30px;");
            html.append("color:gray;}");
            html.append("@media print{body{margin:15px;}");
            html.append("tr{page-break-inside:avoid;}}");
            html.append("</style></head><body>");

            html.append("<h1>SMART COMPLAINT AND GRIEVANCE");
            html.append(" REDRESSAL SYSTEM</h1>");

            html.append("<h3>Complaint Resolution Report</h3>");

            String date = LocalDateTime.now().format(
                DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm:ss")
            );

            html.append("<p><b>Generated Date:</b> ")
                .append(date).append("</p>");

            html.append("<div class='cards'>");

            addCard(html, "Total Complaints",
                    manager.getAllComplaints().size());

            addCard(html, "Submitted",
                    manager.getCount("Submitted"));

            addCard(html, "In Progress",
                    manager.getCount("In Progress"));

            addCard(html, "Resolved",
                    manager.getCount("Resolved"));

            html.append("</div>");

            html.append("<h3>Complaint Details</h3>");

            html.append("<table><tr>");

            String[] headings = {
                "Complaint ID", "Name", "Category",
                "Department", "Priority", "Status",
                "Date", "Remarks"
            };

            for (String heading : headings) {
                html.append("<th>").append(escape(heading))
                    .append("</th>");
            }

            html.append("</tr>");

            for (Complaint c : manager.getAllComplaints()) {

                html.append("<tr>");

                addCell(html, c.getComplaintId());
                addCell(html, c.getName());
                addCell(html, c.getCategory());
                addCell(html, c.getDepartment());
                addCell(html, c.getPriority());
                addCell(html, c.getStatus());
                addCell(html, c.getDate());
                addCell(html, c.getRemarks());

                html.append("</tr>");
            }

            html.append("</table>");

            html.append("<h3>Complaint History</h3>");

            for (Complaint c : manager.getAllComplaints()) {

                html.append("<p><b>")
                    .append(escape(c.getComplaintId()))
                    .append(" - ")
                    .append(escape(c.getName()))
                    .append("</b></p><ul>");

                for (String entry : c.getHistory()) {

                    html.append("<li>")
                        .append(escape(entry))
                        .append("</li>");
                }

                html.append("</ul>");
            }

            html.append("<div class='footer'>");
            html.append("Generated by Smart Complaint Management System");
            html.append("</div>");

            html.append("</body></html>");

            File report = new File("Complaint_Report.html");

            Files.writeString(
                report.toPath(),
                html.toString(),
                StandardCharsets.UTF_8
            );

            if (Desktop.isDesktopSupported()) {

                Desktop.getDesktop().browse(report.toURI());

                JOptionPane.showMessageDialog(null,
                    "Report generated successfully!\n\n" +
                    "The report is open in your browser.\n" +
                    "Press Ctrl + P and select Save as PDF.");
            } else {

                JOptionPane.showMessageDialog(null,
                    "Report created at: " + report.getAbsolutePath());
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null,
                "Report Error: " + e.getMessage());
        }
    }

    private static void addCard(
            StringBuilder html, String title, int value) {

        html.append("<div class='card'><h3>")
            .append(escape(title))
            .append("</h3><h2>")
            .append(value)
            .append("</h2></div>");
    }

    private static void addCell(StringBuilder html, String value) {

        html.append("<td>")
            .append(escape(value))
            .append("</td>");
    }

    private static String escape(String value) {

        if (value == null) {
            return "";
        }

        return value.replace("&", "&amp;")
                    .replace("<", "&lt;")
                    .replace(">", "&gt;")
                    .replace("\"", "&quot;")
                    .replace("'", "&#39;");
    }
}
